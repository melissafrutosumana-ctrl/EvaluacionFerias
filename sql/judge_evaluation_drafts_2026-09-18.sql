-- Borradores temporales de evaluaciones de jueces.
-- Aplicar después de fix_security_critical.sql y las migraciones de seguridad.
-- Los borradores duran 24 horas desde el último guardado y se eliminan al
-- completar la evaluación mediante delete_judge_evaluation_draft().

BEGIN;

CREATE TABLE IF NOT EXISTS public.judge_evaluation_drafts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  juez_id BIGINT NOT NULL REFERENCES public.usuarios(id) ON DELETE CASCADE,
  proyecto_id BIGINT NOT NULL REFERENCES public.proyectos_ferias(id) ON DELETE CASCADE,
  tipo_evaluacion TEXT NOT NULL DEFAULT 'Exposición',
  draft_data JSONB NOT NULL DEFAULT '{}'::JSONB,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  expires_at TIMESTAMPTZ NOT NULL DEFAULT now() + INTERVAL '24 hours',
  CONSTRAINT judge_evaluation_drafts_data_object
    CHECK (jsonb_typeof(draft_data) = 'object'),
  CONSTRAINT judge_evaluation_drafts_tipo_check
    CHECK (btrim(tipo_evaluacion) <> ''),
  CONSTRAINT judge_evaluation_drafts_unique_judge_project_type
    UNIQUE (juez_id, proyecto_id, tipo_evaluacion)
);

CREATE INDEX IF NOT EXISTS idx_judge_evaluation_drafts_expires
  ON public.judge_evaluation_drafts (expires_at);

CREATE INDEX IF NOT EXISTS idx_judge_evaluation_drafts_judge
  ON public.judge_evaluation_drafts (juez_id, updated_at DESC);

ALTER TABLE public.judge_evaluation_drafts ENABLE ROW LEVEL SECURITY;

-- El cliente solo usa las funciones SECURITY DEFINER; no hay acceso directo
-- a la tabla, incluso si el rol anon/authenticated consigue inspeccionarla.
REVOKE ALL ON TABLE public.judge_evaluation_drafts FROM PUBLIC, anon, authenticated;
DO $block$
BEGIN
  IF to_regclass('public.judge_evaluation_drafts_id_seq') IS NOT NULL THEN
    REVOKE ALL ON SEQUENCE public.judge_evaluation_drafts_id_seq FROM PUBLIC, anon, authenticated;
  END IF;
END;
$block$;

CREATE OR REPLACE FUNCTION public.save_judge_evaluation_draft(
  p_session_token TEXT,
  p_project_id BIGINT,
  p_tipo_evaluacion TEXT,
  p_draft_data JSONB
)
RETURNS TABLE(
  proyecto_id BIGINT,
  tipo_evaluacion TEXT,
  draft_data JSONB,
  updated_at TIMESTAMPTZ,
  expires_at TIMESTAMPTZ
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $function$
DECLARE
  v_user_id BIGINT;
  v_tipo TEXT := NULLIF(btrim(p_tipo_evaluacion), '');
  v_proyecto_id BIGINT;
  v_tipo_evaluacion TEXT;
  v_draft_data JSONB;
  v_updated_at TIMESTAMPTZ;
  v_expires_at TIMESTAMPTZ;
BEGIN
  SELECT s.user_id
    INTO v_user_id
    FROM public.app_sessions s
   WHERE s.session_id = p_session_token
     AND s.expires_at > now()
     AND lower(btrim(s.role_name)) = 'juez';

  IF v_user_id IS NULL THEN
    RAISE EXCEPTION 'Invalid session';
  END IF;

  IF v_tipo IS NULL THEN
    RAISE EXCEPTION 'Evaluation type is required';
  END IF;

  IF jsonb_typeof(COALESCE(p_draft_data, '{}'::JSONB)) <> 'object' THEN
    RAISE EXCEPTION 'Draft data must be a JSON object';
  END IF;

  -- Impide escribir borradores para proyectos/tipos que no pertenecen al juez.
  IF NOT EXISTS (
    SELECT 1
     FROM public.asignaciones_jueces a
     WHERE a.juez_id = v_user_id
       AND a.proyecto_id = p_project_id
       AND COALESCE(a.tipo_evaluacion, 'Exposición') = v_tipo
  ) THEN
    RAISE EXCEPTION 'Project is not assigned to this judge';
  END IF;

  INSERT INTO public.judge_evaluation_drafts AS d
    (juez_id, proyecto_id, tipo_evaluacion, draft_data, updated_at, expires_at)
  VALUES
    (v_user_id, p_project_id, v_tipo, COALESCE(p_draft_data, '{}'::JSONB), now(),
     now() + INTERVAL '24 hours')
  ON CONFLICT ON CONSTRAINT judge_evaluation_drafts_unique_judge_project_type
  DO UPDATE SET
    draft_data = EXCLUDED.draft_data,
    updated_at = now(),
    expires_at = now() + INTERVAL '24 hours';

  -- Carga el registro actualizado en las variables de salida. Separar el
  -- INSERT del SELECT evita la ambigüedad entre nombres de columnas y
  -- variables OUT generadas por RETURNS TABLE.
  SELECT d.proyecto_id, d.tipo_evaluacion, d.draft_data, d.updated_at, d.expires_at
    INTO v_proyecto_id, v_tipo_evaluacion, v_draft_data, v_updated_at, v_expires_at
    FROM public.judge_evaluation_drafts d
   WHERE d.juez_id = v_user_id
     AND d.proyecto_id = p_project_id
     AND d.tipo_evaluacion = v_tipo;

  proyecto_id := v_proyecto_id;
  tipo_evaluacion := v_tipo_evaluacion;
  draft_data := v_draft_data;
  updated_at := v_updated_at;
  expires_at := v_expires_at;

  RETURN NEXT;
END;
$function$;

CREATE OR REPLACE FUNCTION public.get_judge_evaluation_draft(
  p_session_token TEXT,
  p_project_id BIGINT,
  p_tipo_evaluacion TEXT
)
RETURNS TABLE(
  proyecto_id BIGINT,
  tipo_evaluacion TEXT,
  draft_data JSONB,
  updated_at TIMESTAMPTZ,
  expires_at TIMESTAMPTZ
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $function$
DECLARE
  v_user_id BIGINT;
  v_tipo TEXT := NULLIF(btrim(p_tipo_evaluacion), '');
BEGIN
  SELECT s.user_id
    INTO v_user_id
    FROM public.app_sessions s
   WHERE s.session_id = p_session_token
     AND s.expires_at > now()
     AND lower(btrim(s.role_name)) = 'juez';

  IF v_user_id IS NULL THEN
    RAISE EXCEPTION 'Invalid session';
  END IF;

  -- Borra de forma oportunista el registro vencido y no devuelve datos viejos.
  DELETE FROM public.judge_evaluation_drafts d
   WHERE d.juez_id = v_user_id
     AND d.proyecto_id = p_project_id
     AND d.tipo_evaluacion = v_tipo
     AND d.expires_at <= now();

  RETURN QUERY
  SELECT d.proyecto_id, d.tipo_evaluacion, d.draft_data, d.updated_at, d.expires_at
    FROM public.judge_evaluation_drafts d
   WHERE d.juez_id = v_user_id
     AND d.proyecto_id = p_project_id
     AND d.tipo_evaluacion = v_tipo
     AND d.expires_at > now();
END;
$function$;

CREATE OR REPLACE FUNCTION public.delete_judge_evaluation_draft(
  p_session_token TEXT,
  p_project_id BIGINT,
  p_tipo_evaluacion TEXT
)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $function$
DECLARE
  v_user_id BIGINT;
BEGIN
  SELECT s.user_id
    INTO v_user_id
    FROM public.app_sessions s
   WHERE s.session_id = p_session_token
     AND s.expires_at > now()
     AND lower(btrim(s.role_name)) = 'juez';

  IF v_user_id IS NULL THEN
    RAISE EXCEPTION 'Invalid session';
  END IF;

  DELETE FROM public.judge_evaluation_drafts
   WHERE juez_id = v_user_id
     AND proyecto_id = p_project_id
     AND tipo_evaluacion = NULLIF(btrim(p_tipo_evaluacion), '');
END;
$function$;

CREATE OR REPLACE FUNCTION public.cleanup_expired_judge_evaluation_drafts()
RETURNS INTEGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $function$
DECLARE
  v_deleted INTEGER;
BEGIN
  DELETE FROM public.judge_evaluation_drafts WHERE expires_at <= now();
  GET DIAGNOSTICS v_deleted = ROW_COUNT;
  RETURN v_deleted;
END;
$function$;

REVOKE ALL ON FUNCTION public.save_judge_evaluation_draft(TEXT, BIGINT, TEXT, JSONB) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.get_judge_evaluation_draft(TEXT, BIGINT, TEXT) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.delete_judge_evaluation_draft(TEXT, BIGINT, TEXT) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.cleanup_expired_judge_evaluation_drafts() FROM PUBLIC;

GRANT EXECUTE ON FUNCTION public.save_judge_evaluation_draft(TEXT, BIGINT, TEXT, JSONB) TO anon, authenticated;
GRANT EXECUTE ON FUNCTION public.get_judge_evaluation_draft(TEXT, BIGINT, TEXT) TO anon, authenticated;
GRANT EXECUTE ON FUNCTION public.delete_judge_evaluation_draft(TEXT, BIGINT, TEXT) TO anon, authenticated;

COMMIT;

